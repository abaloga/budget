#!/usr/bin/env node
/**
 * Copies packages/core/src into supabase/functions/_shared/core so the Deno
 * edge functions run the exact same business logic as the clients.
 *
 * Why a copy: the Supabase function bundler only reliably resolves files under
 * supabase/functions. The copy is committed (so any deploy path works) and
 * `npm run core:check` (part of `npm run verify` and CI) fails if it drifts.
 *
 *   node scripts/sync-core-to-functions.mjs          # write
 *   node scripts/sync-core-to-functions.mjs --check  # verify only
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/core/src');
const dest = join(root, 'supabase/functions/_shared/core');
const check = process.argv.includes('--check');

const HEADER =
  '// GENERATED by scripts/sync-core-to-functions.mjs from packages/core/src — DO NOT EDIT.\n' +
  '// Edit packages/core and run `npm run core:sync`.\n';

const files = readdirSync(src).filter((f) => f.endsWith('.ts'));
const expected = new Map(files.map((f) => [f, HEADER + readFileSync(join(src, f), 'utf8')]));

if (check) {
  const problems = [];
  const actual = existsSync(dest) ? readdirSync(dest).filter((f) => f.endsWith('.ts')) : [];
  for (const [f, content] of expected) {
    const p = join(dest, f);
    if (!existsSync(p) || readFileSync(p, 'utf8') !== content) problems.push(`out of date: ${f}`);
  }
  for (const f of actual) if (!expected.has(f)) problems.push(`stale: ${f}`);
  if (problems.length) {
    console.error('supabase/functions/_shared/core is out of sync with packages/core:');
    for (const p of problems) console.error(`  - ${p}`);
    console.error('Run: npm run core:sync');
    process.exit(1);
  }
  console.log('core copy is in sync');
} else {
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });
  for (const [f, content] of expected) writeFileSync(join(dest, f), content);
  console.log(`copied ${expected.size} files to supabase/functions/_shared/core`);
}
